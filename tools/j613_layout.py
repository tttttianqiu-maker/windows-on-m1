#!/usr/bin/env python3
"""Derive the J613 (MacBook Air 13", M3) guest layout from the real DRAM base.

The J313 layout in config/j313-guest-layout.json is "M1 DRAM base (0x800000000)
+ fixed offsets". This tool keeps the same offsets but rebases them onto the
DRAM base read from the J613's own ADT (/chosen dram-base, printed by m1n1 at
boot and dumped by scripts/j613-probe.sh), and sizes the guest for its RAM.

It writes:
  config/j613-guest-layout.json
  mu/Platform/MacBookAirM3J613Pkg/J613GuestLayout.dsc.inc
and patches the FD base address in MacBookAirM3J613.fdf.

Standalone on purpose: it re-implements the validation from guest_layout.py
instead of importing it, so it can run anywhere with plain python3.

Usage:
  python3 tools/j613_layout.py --dram-base 0x10000000000 --dram-size 16G [--mu ../mu]
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALIGNMENT = 0x4000
J313_DRAM_BASE = 0x800000000

# Offsets of every DRAM-relative J313 value from the M1 DRAM base.
J313 = {
    "phys_base": 0x850000000,
    "firmware_base": 0x8510B4000,
    "adt_base": 0x851000000,
    "boot_args_base": 0x8533E8000,
    "ramdisk_base": 0x860000000,
    "low_mem_pa": 0x8A0100000,
    # J313 used +0x5F000000; the taller J613 panel (1664 rows, 0x1040000 bytes)
    # would run into the RAM disk at +0x60000000, so start 16 MB earlier.
    "virtual_fb_base": 0x85E000000,
}
FIXED = {
    "layout_version": 1,
    "firmware_max_size": 0x1E00000,
    "adt_max_size": 0xB4000,
    "boot_args_size": 0x4000,
    "ramdisk_max_size": 0x40000000,
    "low_mem_ipa": 0x100000,
    "low_mem_size": 0x3FF00000,
    # J613 internal panel: 2560 x 1664, 32 bpp.
    "virtual_fb_width": 2560,
    "virtual_fb_height": 1664,
    "virtual_fb_stride": 2560 * 4,
    # Virtual devices invented by the hypervisor. Both windows are unpopulated
    # on T8122 (checked against t8122.dtsi), so the J313 values carry over.
    "pci_ecam": 0x690000000,
    "pci_bar_window": 0x400000000,
    "nvme_vintid": 64,
    # dwc3_1 / usb@b02280000 on T8122 (J313: 0x502280000).
    "xhci_base": 0xB02280000,
    "cpu_count": 8,
}
# How much RAM the guest gets, counted from phys_base. J313 (8 GB) ended at
# DRAM base + 8 GB; keep a 1 GB tail for m1n1 / the host side.
HOST_TAIL = 0x40000000


def parse_size(text: str) -> int:
    m = re.fullmatch(r"(\d+)([GgMm]?)", text.strip())
    if not m:
        return int(text, 0)
    n, unit = int(m.group(1)), m.group(2).upper()
    return n << (30 if unit == "G" else 20 if unit == "M" else 0)


def build(dram_base: int, dram_size: int) -> dict:
    layout = dict(FIXED)
    for key, value in J313.items():
        layout[key] = dram_base + (value - J313_DRAM_BASE)
    layout["ram_end"] = dram_base + dram_size - HOST_TAIL
    return layout


def validate(l: dict) -> None:
    aligned = ["phys_base", "ram_end", "firmware_base", "adt_base", "boot_args_base",
               "ramdisk_base", "low_mem_pa", "virtual_fb_base", "pci_ecam",
               "pci_bar_window", "xhci_base"]
    for name in aligned:
        if l[name] % ALIGNMENT:
            raise ValueError(f"{name} {l[name]:#x} is not {ALIGNMENT:#x}-aligned")
    if l["virtual_fb_stride"] < l["virtual_fb_width"] * 4:
        raise ValueError("virtual framebuffer stride is too small")
    fb_size = l["virtual_fb_stride"] * l["virtual_fb_height"]
    ranges = {
        "ADT": (l["adt_base"], l["adt_base"] + l["adt_max_size"]),
        "firmware": (l["firmware_base"], l["firmware_base"] + l["firmware_max_size"]),
        "boot args": (l["boot_args_base"], l["boot_args_base"] + l["boot_args_size"]),
        "virtual framebuffer": (l["virtual_fb_base"], l["virtual_fb_base"] + fb_size),
        "RAM disk": (l["ramdisk_base"], l["ramdisk_base"] + l["ramdisk_max_size"]),
        "low-memory backing": (l["low_mem_pa"], l["low_mem_pa"] + l["low_mem_size"]),
    }
    for name, (s, e) in ranges.items():
        if s < l["phys_base"] or e > l["ram_end"] or s >= e:
            raise ValueError(f"{name} {s:#x}-{e:#x} is outside guest RAM")
    items = list(ranges.items())
    for i, (a, (as_, ae)) in enumerate(items):
        for b, (bs, be) in items[i + 1:]:
            if as_ < be and bs < ae:
                raise ValueError(f"{a} overlaps {b}")
    # The virtual devices must not land inside DRAM.
    dram_lo, dram_hi = l["phys_base"], l["ram_end"]
    for name in ("pci_ecam", "pci_bar_window", "xhci_base"):
        if dram_lo <= l[name] < dram_hi:
            raise ValueError(f"{name} {l[name]:#x} collides with guest DRAM")


def render_dsc(l: dict) -> str:
    return f"""# Generated by tools/j613_layout.py. Do not edit.
[PcdsFixedAtBuild.common]
  # Mu is built for the pinned guest layout shared with the hypervisor. Moving one
  # region independently makes early PrePi dereference an unmapped guest address.
  gAppleSiliconPkgTokenSpaceGuid.PcdBootArgsPointer|0x{l['boot_args_base']:x}
  gAppleSiliconPkgTokenSpaceGuid.PcdAdtPointer|0x{l['adt_base']:x}
  gAppleSiliconPkgTokenSpaceGuid.PcdPreloadedRamdiskBase|0x{l['ramdisk_base']:x}
  gAppleSiliconPkgTokenSpaceGuid.PcdPreloadedRamdiskMaxSize|0x{l['ramdisk_max_size']:x}
  # Windows Boot Manager allocates low physical pages; m1n1 aliases this IPA window
  # to the backing range inside J613 DRAM below.
  gAppleSiliconPkgTokenSpaceGuid.PcdLowMemoryWindowBase|0x{l['low_mem_ipa']:x}
  gAppleSiliconPkgTokenSpaceGuid.PcdLowMemoryWindowSize|0x{l['low_mem_size']:x}
  gAppleSiliconPkgTokenSpaceGuid.PcdLowMemoryWindowBackingBase|0x{l['low_mem_pa']:x}
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dram-base", required=True, type=lambda s: int(s, 0),
                    help="J613 /chosen dram-base (from scripts/j613-probe.sh)")
    ap.add_argument("--dram-size", default="16G", type=parse_size)
    ap.add_argument("--mu", type=Path, default=ROOT / "mu",
                    help="path to the Project Mu checkout")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    layout = build(a.dram_base, a.dram_size)
    validate(layout)
    as_json = {k: (f"{v:#x}" if isinstance(v, int) and k not in (
        "layout_version", "virtual_fb_width", "virtual_fb_height",
        "virtual_fb_stride", "nvme_vintid", "cpu_count") else v)
        for k, v in layout.items()}
    text = json.dumps(as_json, indent=2) + "\n"
    if a.dry_run:
        print(text)
        print(render_dsc(layout))
        return 0

    (ROOT / "config/j613-guest-layout.json").write_text(text)
    pkg = a.mu / "Platform/MacBookAirM3J613Pkg"
    (pkg / "J613GuestLayout.dsc.inc").write_text(render_dsc(layout))
    fdf = pkg / "MacBookAirM3J613.fdf"
    src = fdf.read_text()
    new, n = re.subn(r"(BaseAddress\s*=\s*)0x[0-9A-Fa-f]+(\|gArmTokenSpaceGuid\.PcdFdBaseAddress)",
                     rf"\g<1>0x{layout['firmware_base']:X}\2", src)
    if n != 1:
        print("could not find the FD BaseAddress line in the FDF", file=sys.stderr)
        return 1
    fdf.write_text(new)
    print(f"J613 layout written (firmware at {layout['firmware_base']:#x}, "
          f"guest RAM {layout['phys_base']:#x}-{layout['ram_end']:#x})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
